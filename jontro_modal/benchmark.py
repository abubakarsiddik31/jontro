"""Teacher-forced Jontro benchmark on Modal (HF generate), for any arm in the arm grammar.

Prompts are precomputed by scripts/build_benchmark_prompts.py (exact repo prompts, gold prefix at every
decision point). Output rows match the repo runner's format, so scripts/score_benchmark.py can score
them with the repo's own scorer. ``stride`` > 1 samples every stride-th decision point (screening runs).
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

from jontro_modal.arms import adapter_name, attach, label
from jontro_modal.retention import Generator
from jontro_modal.toolparse import parse_tool_calls

# Modal paths by default; override them to run off Modal.
PROMPTS = Path(os.environ.get("JONTRO_BENCH_PROMPTS", "/benchmark/teacher_forced_test.jsonl"))
OUT = Path(os.environ.get("JONTRO_BENCH_OUT", "/out/benchmark"))


def run_benchmark(base_model: str, arms: list[str], stride: int = 4, max_new: int = 300, bs: int = 8) -> dict:
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    rows = [json.loads(line) for line in PROMPTS.open()]
    rows = [r for i, r in enumerate(rows) if i % stride == 0]
    tok = AutoTokenizer.from_pretrained(base_model)
    base = AutoModelForCausalLM.from_pretrained(base_model, dtype=torch.bfloat16, device_map={"": 0})
    pm = attach(base, arms)
    model = pm if pm is not None else base
    model.eval()
    gen = Generator(model, tok)
    order = sorted(range(len(rows)), key=lambda i: sum(len(m.get("content") or "") for m in rows[i]["messages"]))
    OUT.mkdir(parents=True, exist_ok=True)
    summary = {}
    for arm in arms:
        t0 = time.time()
        ctx = pm.disable_adapter() if (arm == "base" and pm is not None) else _Null()
        if arm != "base":
            pm.set_adapter(adapter_name(arm))
        partial = OUT / f"{label(arm)}.partial.jsonl"
        OUT.mkdir(parents=True, exist_ok=True)
        outs: list = [None] * len(rows)
        for i, g in _load_partial(partial).items():
            outs[i] = g
        if any(o is not None for o in outs):
            print(f"{label(arm)}: resuming, {sum(o is not None for o in outs)}/{len(rows)} done", flush=True)
        with ctx:
            for k in range(0, len(order), 64):  # progress is saved after every chunk
                idx = [i for i in order[k:k + 64] if outs[i] is None]
                if not idx:
                    continue
                gens = gen.generate([{"messages": rows[i]["messages"], "tools": rows[i]["tools"]} for i in idx], max_new, bs)
                for j, g in zip(idx, gens):
                    outs[j] = g
                _append_partial(partial, idx, gens)
                print(f"{label(arm)}: {sum(o is not None for o in outs)}/{len(rows)}", flush=True)
        n_calls = 0
        with (OUT / f"{label(arm)}.jsonl").open("w") as f:
            for r, g in zip(rows, outs):
                calls = parse_tool_calls(g["output"], r["tools"])
                n_calls += bool(calls)
                f.write(json.dumps({"example_id": r["example_id"], "step": r["step"], "protocol": "teacher_forced",
                                    "model": label(arm), "tool_calls": calls, "raw_text": g["output"], "error": None},
                                   ensure_ascii=False) + "\n")
        partial.unlink(missing_ok=True)
        summary[label(arm)] = {"steps": len(rows), "emitted_call": n_calls, "seconds": round(time.time() - t0)}
        print(label(arm), summary[label(arm)], flush=True)
    return summary


def _load_partial(path: Path) -> dict[int, dict]:
    """Rows already generated by an interrupted run (index -> generation), so a restart resumes."""
    if not path.exists():
        return {}
    done = {}
    for line in path.read_text().splitlines():
        try:
            r = json.loads(line)
        except json.JSONDecodeError:  # torn last line from a killed process
            continue
        done[r["i"]] = r["g"]
    return done


def _append_partial(path: Path, idx: list[int], gens: list[dict]) -> None:
    with path.open("a") as f:
        for i, g in zip(idx, gens):
            f.write(json.dumps({"i": i, "g": {"output": g["output"], "finished": g["finished"]}},
                               ensure_ascii=False) + "\n")


class _Null:
    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False
